"""Training-free baselines. Each predicts labels in {-1, 0, 1} from raw text.

Important for interpretation: the dataset's labels were generated by TextBlob (sign of polarity), so on
silver labels TextBlobClassifier is the label source, not a competitor. It exists to quantify that, and
to be scored against human labels on the gold set.
"""
from typing import Iterable, List

import numpy as np

_HINT = "install requirements/eval.txt"


class MajorityClassifier:
    name = "Majority"

    def fit(self, texts: Iterable[str], labels: Iterable[int]) -> "MajorityClassifier":
        values, counts = np.unique(np.asarray(list(labels)).astype(int), return_counts=True)
        self.label_ = int(values[counts.argmax()])
        return self

    def predict(self, texts: Iterable[str]) -> np.ndarray:
        return np.full(len(list(texts)), self.label_, dtype=int)


class TextBlobClassifier:
    """sign(polarity); exactly 0.0 is neutral. Reproduces how the dataset labels were made."""
    name = "TextBlob"

    def __init__(self):
        try:
            from textblob import TextBlob
        except ImportError as e:
            raise ImportError(f"textblob is required: {_HINT}") from e
        self._TextBlob = TextBlob

    def predict_one(self, text: str) -> int:
        polarity = self._TextBlob(str(text)).sentiment.polarity
        return int(np.sign(polarity))

    def predict(self, texts: Iterable[str]) -> np.ndarray:
        return np.array([self.predict_one(t) for t in texts], dtype=int)


class VaderClassifier:
    """VADER compound score with the conventional +/-0.05 neutral band (Hutto & Gilbert, 2014)."""
    name = "VADER"

    def __init__(self, threshold: float = 0.05):
        try:
            from vaderSentiment.vaderSentiment import SentimentIntensityAnalyzer
        except ImportError as e:
            raise ImportError(f"vaderSentiment is required: {_HINT}") from e
        self._analyzer = SentimentIntensityAnalyzer()
        self.threshold = threshold

    def predict_one(self, text: str) -> int:
        compound = self._analyzer.polarity_scores(str(text))["compound"]
        if compound >= self.threshold:
            return 1
        if compound <= -self.threshold:
            return -1
        return 0

    def predict(self, texts: Iterable[str]) -> np.ndarray:
        return np.array([self.predict_one(t) for t in texts], dtype=int)
